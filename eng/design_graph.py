def slug(task_id: str) -> str:
    return 'task-' + task_id.lower().replace('.', '-')

def key_of(item_id: str) -> str:
    """Ref, branch and ledger file key of an ID: lower case, dots replaced by hyphens.

    Git for Windows rejects refs and paths whose stem is a reserved device name (CON, PRN, AUX,
    NUL, COM1-9, LPT1-9) followed by an extension, so `con.02` can be neither a claim branch, a
    task branch nor a ledger file on the Windows workstations. Upper case is avoided because
    `CON-02` would read as a corpus identifier in generated Design views."""
    return item_id.lower().replace('.', '-')

def role_id(repo: str) -> str:
    return f'integration:{repo}'

def load_json(path: Path):
    def hook(pairs):
        out = {}
        for k, v in pairs:
            if k in out:
                raise Fail(f'duplicate JSON key {k} in {path}')
            out[k] = v
        return out
    return json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=hook)

def wp_files(design: Path) -> dict[str, Path]:
    files = {}
    for p in sorted((design / WP_REL).glob('[0-9][0-9]-*.md')):
        files[p.name[:2]] = p
    return files

def substeps(design: Path) -> dict[str, dict]:
    """Every active numbered substep, parsed from the obligation catalogue headings."""
    out = {}
    for wp, p in wp_files(design).items():
        for line in p.read_text(encoding='utf-8').splitlines():
            m = re.match(r'^### WP-(\d{2})\.(\d{2}) — (.+?)\s*$', line)
            if m:
                sid = f'WP-{m[1]}.{m[2]}'
                out[sid] = {'id': sid, 'wp': m[1], 'title': m[3].rstrip('.'), 'file': p.name}
    return out

def anchor_homes(design: Path) -> dict[str, list[str]]:
    """Map rule identifiers to the documents that define `rule-<id>` anchors."""
    homes = defaultdict(list)
    for p in sorted((design / 'docs').rglob('*.md')):
        rel = p.relative_to(design).as_posix()
        if rel.startswith('docs/deprecated-inputs/') and not rel.endswith('README.md'):
            continue
        for a in ANCHOR.findall(p.read_text(encoding='utf-8')):
            if a.startswith('rule-'):
                homes[a[5:]].append(rel)
    return homes

class Linker:
    def __init__(self, design: Path, from_rel: str):
        self.design = design
        self.from_dir = str(Path(from_rel).parent.as_posix())
        self.homes = anchor_homes(design)
        self.unknown: set[str] = set()

    def rel(self, target_rel: str) -> str:
        import posixpath
        return posixpath.relpath(target_rel, self.from_dir)

    def home(self, ident: str) -> str | None:
        key = ident.lower()
        m = SUBSTEP.match(ident) or re.match(r'^WP-(\d{2})$', ident)
        if m:
            files = wp_files(self.design)
            f = files.get(m[1])
            return f'{WP_REL}/{f.name}' if f else None
        cands = self.homes.get(key, [])
        if not cands:
            return None
        if len(cands) == 1:
            return cands[0]
        for pref in PREFERRED_HOMES:
            if pref in cands:
                return pref
        return cands[0]

    def link(self, ident: str) -> str:
        h = self.home(ident)
        if not h:
            self.unknown.add(ident)
            return ident
        return f'[{ident}]({self.rel(h)}#rule-{ident.lower()})'

    def text(self, s: str) -> str:
        """Link every corpus identifier outside existing links; strip code spans around IDs."""
        if not s:
            return ''
        s = s.replace('\r', ' ').replace('\n', ' ').replace('|', '/')
        s = re.sub(r'`([^`]*)`', lambda m: m[1] if CORPUS_ID.search(m[1]) else m[0], s)
        out, pos = [], 0
        spans = [m.span() for m in LINK.finditer(s)]
        for m in CORPUS_ID.finditer(s):
            if any(a <= m.start() < b for a, b in spans):
                continue
            out.append(s[pos:m.start()])
            out.append(self.link(m[0]))
            pos = m.end()
        out.append(s[pos:])
        return ''.join(out)

class Graph:
    def __init__(self, design: Path):
        self.design = design
        self.data = load_json(design / GRAPH_REL)
        self.tasks = {t['id']: t for t in self.data['tasks']}
        self.lanes = {l['id']: l for l in self.data['lanes']}
        self.repos = {r['id']: r for r in self.data['repositories']}
        self.subs = {s['id']: s for s in self.data.get('substitutes', [])}
        self.res = {r['id']: r for r in self.data.get('sharedResources', [])}
        self.pobs = {p['id']: p for p in self.data.get('packageObligations', [])}
        self.gates = {g['gate']: g for g in self.data.get('gates', [])}
        self.catalogue = substeps(design)
        # Adoption slices (DLV-22): one independently claimable unit per repository and lane. They are
        # scheduling nodes like tasks; the repository adoption task completes after all of its slices.
        self.slices = {s['id']: s for s in self.data.get('adoptionSlices', [])}
        self.slice_of = {(s['repo'], s['lane']): s['id'] for s in self.slices.values()}
        for s in self.slices.values():
            self.tasks[s['id']] = {
                'id': s['id'], 'title': s['title'], 'lane': 'adoption', 'repo': s['repo'], 'kind': 'adoption',
                'size': 'S', 'slice': True, 'lanesOpened': s['lane'], 'baseline': {'state': 'not-started'},
                'obligations': [{'ref': 'P2-018', 'part': f'adoption slice for {s["repo"]} lane {s["lane"]}'}],
                'start': [{'type': 'artifact', 'task': ROOT_ADOPTION, 'need': 'frozen baseline record',
                           'why': 'every slice classifies against the same frozen heads and receipts'}],
                'complete': []}
            parent = self.tasks.get(s['adoptionTask'])
            if parent is not None and not any(e['task'] == s['id'] for e in parent['complete']):
                parent['complete'].append({'type': 'integration', 'task': s['id'], 'need': 'slice recorded',
                                           'why': 'the repository adoption record closes after every slice of the repository'})

    def slice_tasks(self, sid):
        s = self.slices[sid]
        return sorted(tid for tid, t in self.tasks.items()
                      if not t.get('slice') and t['repo'] == s['repo'] and t['lane'] == s['lane'])

    def start_edges(self, t):
        return [e for e in t.get('start', [])]

    def complete_edges(self, t):
        return [e for e in t.get('complete', [])]

    def entry(self, tid):
        """Adoption entry of a task (DLV-22): the slice of its repository and lane, if any."""
        t = self.tasks[tid]
        if t.get('kind') == 'adoption' or t['baseline']['state'] == 'accepted':
            return None
        sid = self.slice_of.get((t['repo'], t['lane']))
        if sid:
            return sid
        a = self.repos.get(t['repo'], {}).get('adoptionTask')
        return None if not a or a == tid else a

    def starts(self, tid):
        t = self.tasks[tid]
        s = [e['task'] for e in t.get('start', [])]
        a = self.entry(tid)
        return s + ([a] if a and a not in s else [])

    def preds(self, tid):
        t = self.tasks[tid]
        return self.starts(tid) + [e['task'] for e in t.get('complete', [])]

    def succ_map(self):
        succ = defaultdict(set)
        for tid, t in self.tasks.items():
            for e in t.get('start', []) + t.get('complete', []):
                succ[e['task']].add(tid)
        return succ

    def events(self):
        """Event graph (DLV-21): D(t)=delivered, C(t)=complete.

        D(t) needs D(s) for each contract/artifact/design start prerequisite s (and the adoption entry),
        C(s) for each release prerequisite; C(t) needs D(t) and C(s) for each completion prerequisite s.
        """
        adj = defaultdict(set)
        for tid, t in self.tasks.items():
            for e in t.get('start', []):
                adj[('D', tid)].add(('C' if e['type'] == 'release' else 'D', e['task']))
            ent = self.entry(tid)
            if ent:
                adj[('D', tid)].add(('C', ent))
            adj[('C', tid)].add(('D', tid))
            for e in t.get('complete', []):
                adj[('C', tid)].add(('C', e['task']))
        return adj

    def event_order(self):
        adj = self.events()
        nodes = {(k, t) for t in self.tasks for k in ('D', 'C')}
        indeg = {n: 0 for n in nodes}
        rev = defaultdict(set)
        for n, ps in adj.items():
            for p in ps:
                if p in nodes:
                    indeg[n] += 1
                    rev[p].add(n)
        q = deque(sorted(n for n, d in indeg.items() if d == 0))
        order = []
        while q:
            n = q.popleft()
            order.append(n)
            for m in sorted(rev.get(n, ())):
                indeg[m] -= 1
                if indeg[m] == 0:
                    q.append(m)
        stuck = sorted({t for (k, t), d in indeg.items() if d > 0})
        return order, stuck

    def topo(self):
        indeg = {t: 0 for t in self.tasks}
        succ = self.succ_map()
        for tid in self.tasks:
            for p in set(self.preds(tid)):
                if p in self.tasks:
                    indeg[tid] += 1
        q = deque(sorted(t for t, d in indeg.items() if d == 0))
        order = []
        while q:
            n = q.popleft()
            order.append(n)
            for s in sorted(succ.get(n, ())):
                indeg[s] -= 1
                if indeg[s] == 0:
                    q.append(s)
        return order, [t for t, d in indeg.items() if d > 0]

    def ancestors(self, tid, cache={}):
        key = (id(self), tid)
        if key in cache:
            return cache[key]
        seen, stack = set(), list(self.preds(tid))
        while stack:
            p = stack.pop()
            if p in seen or p not in self.tasks:
                continue
            seen.add(p)
            stack.extend(self.preds(p))
        cache[key] = seen
        return seen

    def obligation_map(self):
        m = defaultdict(list)
        for t in self.data['tasks']:
            for o in t.get('obligations', []):
                m[o['ref']].append((t['id'], o.get('part', '')))
        return m

def validate(g: Graph) -> tuple[list[str], list[str]]:
    errors, warnings = [], []
    ids = [t['id'] for t in g.data['tasks']]
    for tid, n in Counter(ids).items():
        if n > 1:
            errors.append(f'duplicate task id {tid}')
    required = ['id', 'title', 'lane', 'repo', 'kind', 'size', 'obligations', 'outcome', 'start',
                'complete', 'writes', 'validation', 'evidence', 'baseline']
    for t in g.data['tasks']:
        tid = t.get('id', '?')
        for f in required:
            if f not in t:
                errors.append(f'{tid}: missing field {f}')
        if not TASK_ID.match(tid):
            errors.append(f'{tid}: invalid task id format')
        if CORPUS_ID.search(t.get('title', '')):
            errors.append(f'{tid}: title contains a corpus identifier; keep identifiers in obligations')
        if t.get('lane') not in g.lanes:
            errors.append(f'{tid}: unknown lane {t.get("lane")}')
        elif not tid.startswith(g.lanes[t['lane']]['prefix'] + '.'):
            errors.append(f'{tid}: prefix does not match lane {t["lane"]}')
        if t.get('repo') not in g.repos:
            errors.append(f'{tid}: unknown repository {t.get("repo")}')
        for r in t.get('alsoTouches', []):
            if r not in g.repos:
                errors.append(f'{tid}: unknown touched repository {r}')
        if t.get('kind') not in KINDS:
            errors.append(f'{tid}: unknown kind {t.get("kind")}')
        if t.get('size') not in SIZES:
            errors.append(f'{tid}: unknown size {t.get("size")}')
        if not t.get('obligations'):
            errors.append(f'{tid}: no obligations')
        for o in t.get('obligations', []):
            ref = o.get('ref', '')
            if SUBSTEP.match(ref):
                if ref not in g.catalogue:
                    errors.append(f'{tid}: obligation {ref} is not an active substep')
            elif POB_ID.match(ref):
                if ref not in g.pobs:
                    errors.append(f'{tid}: unknown package obligation {ref}')
            elif DECISION.match(ref):
                if t.get('kind') not in {'adoption', 'governance'}:
                    errors.append(f'{tid}: decision obligation {ref} is reserved for adoption/governance tasks')
            else:
                errors.append(f'{tid}: invalid obligation reference {ref}')
            if not o.get('part'):
                errors.append(f'{tid}: obligation {ref} lacks part text')
        for kind, allowed in (('start', START_TYPES), ('complete', COMPLETE_TYPES)):
            seen = set()
            for e in t.get(kind, []):
                tgt = e.get('task')
                if e.get('type') not in allowed:
                    errors.append(f'{tid}: {kind} edge to {tgt} has invalid type {e.get("type")}')
                if tgt not in g.tasks:
                    errors.append(f'{tid}: {kind} edge to unknown task {tgt}')
                if tgt == tid:
                    errors.append(f'{tid}: self edge')
                if tgt in seen:
                    errors.append(f'{tid}: duplicate {kind} edge to {tgt}')
                seen.add(tgt)
                if not (e.get('why') or '').strip() or not (e.get('need') or '').strip():
                    errors.append(f'{tid}: {kind} edge to {tgt} lacks need/why')
                if e.get('type') == 'release' and t.get('kind') not in {'release', 'acceptance'}:
                    errors.append(f'{tid}: release edge on a non-release task')
        for s in t.get('substitutes', []):
            if s not in g.subs:
                errors.append(f'{tid}: unknown substitute {s}')
        for sh in t.get('shared', []):
            if sh.get('resource') not in g.res:
                errors.append(f'{tid}: unknown shared resource {sh.get("resource")}')
            if sh.get('mode') not in MODES:
                errors.append(f'{tid}: invalid shared mode {sh.get("mode")}')
        for w in t.get('writes', []):
            repo = w.split(':', 1)[0]
            if ':' not in w or (repo not in g.repos and repo != '*'):
                errors.append(f'{tid}: invalid write scope {w}')
            if w.startswith('Plan:ledger/tasks/') and not re.fullmatch(r'Plan:ledger/tasks/[a-z0-9]+(?:-[a-z0-9]+)*\.md', w):
                errors.append(f'{tid}: ledger record {w} must use the lower-case hyphenated task key (DLV-26)')
        b = t.get('baseline', {})
        if b.get('state') not in BASELINE:
            errors.append(f'{tid}: invalid baseline state {b.get("state")}')
        if b.get('state') == 'accepted' and not b.get('evidence'):
            errors.append(f'{tid}: accepted baseline without evidence')
    for l in g.lanes.values():
        if l['repo'] not in g.repos and l['repo'] != 'multiple':
            errors.append(f'lane {l["id"]}: unknown repository {l["repo"]}')
    # Adoption slices: exactly one per (repository, lane) pair that has non-adoption tasks (DLV-22).
    pairs = {(t['repo'], t['lane']) for t in g.data['tasks'] if t.get('kind') != 'adoption'}
    seen_pairs = Counter((s['repo'], s['lane']) for s in g.slices.values())
    for sid, s in g.slices.items():
        if not SLICE_ID.match(sid):
            errors.append(f'{sid}: invalid adoption slice id')
        parent = g.repos.get(s.get('repo'), {}).get('adoptionTask')
        if s.get('adoptionTask') != parent or not sid.startswith(f'{parent}.') or sid != f'{parent}.{s.get("lane")}':
            errors.append(f'{sid}: slice does not belong to the adoption task of {s.get("repo")}')
        if s.get('lane') not in g.lanes:
            errors.append(f'{sid}: unknown lane {s.get("lane")}')
        if not s.get('title'):
            errors.append(f'{sid}: missing title')
    for pair in pairs:
        if g.repos.get(pair[0], {}).get('adoptionTask') and seen_pairs.get(pair, 0) != 1:
            errors.append(f'repository {pair[0]} lane {pair[1]}: expected exactly one adoption slice, found {seen_pairs.get(pair, 0)}')
    for pair in seen_pairs:
        if pair not in pairs:
            errors.append(f'adoption slice for {pair[0]}/{pair[1]} has no tasks')
    # Package acceptance is a roll-up, never a start barrier for work outside the package (DLV-35).
    accept = {t['id']: t['packageAcceptance'] for t in g.data['tasks'] if t.get('packageAcceptance')}
    for tid, wp in accept.items():
        if not re.match(r'^WP-\d{2}$', wp):
            errors.append(f'{tid}: invalid packageAcceptance {wp}')
    for t in g.data['tasks']:
        if t.get('kind') == 'release' or t.get('packageAcceptance'):
            continue
        for e in t.get('start', []):
            wp = accept.get(e.get('task'))
            if wp and not any(o['ref'].startswith((wp + '.', wp + ':')) for o in t.get('obligations', [])):
                errors.append(f'{t["id"]}: start prerequisite on package acceptance task {e["task"]} ({wp}); depend on the '
                              f'producing tasks or use a completion prerequisite (DLV-35)')
    _, stuck = g.event_order()
    if stuck:
        errors.append(f'unsatisfiable prerequisites (deadlock) among {len(stuck)} tasks: {stuck[:12]}')
    # Obligation coverage.
    om = g.obligation_map()
    for sid in g.catalogue:
        if sid not in om:
            errors.append(f'substep {sid} is not mapped to any task')
        elif len(om[sid]) > 1 and any(p.strip().lower() == 'full' for _, p in om[sid]):
            warnings.append(f'substep {sid} mapped by {len(om[sid])} tasks but one claims "full"')
    for pid in g.pobs:
        if pid not in om:
            errors.append(f'package obligation {pid} is not mapped to any task')
    for s in g.pobs.values():
        if not POB_ID.match(s['id']):
            errors.append(f'invalid package obligation id {s["id"]}')
    # Substitutes.
    users = defaultdict(list)
    for t in g.data['tasks']:
        for s in t.get('substitutes', []):
            users[s].append(t['id'])
    for sid, s in g.subs.items():
        if not SUB_ID.match(sid):
            errors.append(f'invalid substitute id {sid}')
        for f in ('standsInFor', 'contract', 'proves', 'realProducer', 'replacedBy', 'realEvidence'):
            if not s.get(f):
                errors.append(f'{sid}: missing {f}')
        if s.get('class') not in SUB_CLASSES:
            errors.append(f'{sid}: class must be value or behavior (DLV-18)')
        rp = s.get('realProducer', [])
        rp = rp if isinstance(rp, list) else [rp]
        rb = s.get('replacedBy')
        for p in rp:
            if p not in g.tasks:
                errors.append(f'{sid}: unknown real producer {p}')
        if rb not in g.tasks:
            errors.append(f'{sid}: unknown replacing task {rb}')
            continue
        anc = g.ancestors(rb)
        for p in rp:
            if p in g.tasks and p != rb and p not in anc:
                errors.append(f'{sid}: replacing task {rb} does not depend on real producer {p}')
        for u in users.get(sid, []):
            if u != rb and u not in anc:
                errors.append(f'{sid}: replacing task {rb} does not depend on consumer {u}')
        if not users.get(sid):
            warnings.append(f'{sid}: substitute not used by any task')
        if g.tasks[rb].get('kind') not in {'integration', 'acceptance', 'release', 'service', 'producer', 'feature'}:
            warnings.append(f'{sid}: replacing task {rb} has kind {g.tasks[rb].get("kind")}')
    # Shared resources.
    for rid, r in g.res.items():
        if not RES_ID.match(rid):
            errors.append(f'invalid shared resource id {rid}')
        if r.get('ownerRepo') not in g.repos and r.get('ownerRepo') not in {'multiple', 'workstation'}:
            errors.append(f'{rid}: unknown owner repository {r.get("ownerRepo")}')
        for f in ('kind', 'owner', 'protocol', 'title'):
            if not r.get(f):
                errors.append(f'{rid}: missing {f}')
    # The same exact file written by two unordered tasks must be a declared shared resource.
    # Different files inside one module directory are ordinary parallel work resolved by Git.
    by_repo = defaultdict(list)
    for t in g.data['tasks']:
        for w in t.get('writes', []):
            repo, path = w.split(':', 1)
            path = path.split(' (', 1)[0].strip()
            if '*' in path or path.endswith('/') or not path:
                continue
            by_repo[repo].append((t['id'], path))
    shared_of = {t['id']: {s['resource'] for s in t.get('shared', [])} for t in g.data['tasks']}
    for repo, items in by_repo.items():
        for i in range(len(items)):
            a, pa = items[i]
            for j in range(i + 1, len(items)):
                b, pb = items[j]
                if a == b:
                    continue
                if pa != pb:
                    continue
                if a in g.ancestors(b) or b in g.ancestors(a):
                    continue
                if shared_of[a] & shared_of[b]:
                    continue
                warnings.append(f'unordered write overlap {a} ~ {b} in {repo}: {pa} / {pb}')
    # Gates.
    for gate, rec in g.gates.items():
        for tid in rec.get('tasks', []):
            if tid not in g.tasks:
                errors.append(f'gate {gate}: unknown task {tid}')
    return errors, warnings

def weights(g: Graph):
    return {tid: SIZES[t['size']] for tid, t in g.tasks.items()}

def _event_weights(g: Graph, done):
    return {('D', t): (0 if t in done else SIZES[g.tasks[t]['size']]) for t in g.tasks} | {('C', t): 0 for t in g.tasks}

def critical_path(g: Graph, done: set[str] | None = None):
    """Longest weighted chain on the event graph; a task's work sits on its delivery event."""
    done = done or set()
    order, _ = g.event_order()
    adj = g.events()
    w = _event_weights(g, done)
    finish, prev = {}, {}
    for n in order:
        best, arg = 0, None
        for p in sorted(adj.get(n, ())):
            if finish.get(p, 0) > best:
                best, arg = finish[p], p
        finish[n] = best + w[n]
        prev[n] = arg
    end = max(sorted(finish), key=lambda k: finish[k])
    length = finish[end]
    path = []
    while end:
        if end[0] == 'D' and end[1] not in path:
            path.append(end[1])
        end = prev[end]
    return list(reversed(path)), length

def levels(g: Graph, done: set[str] | None = None):
    """Delivery level: longest chain of unfinished prerequisite deliveries before a task can be delivered."""
    done = done or set()
    order, _ = g.event_order()
    adj = g.events()
    lvl = {}
    for n in order:
        ps = [lvl[p] for p in adj.get(n, ()) if p in lvl]
        base = max(ps) if ps else 0
        lvl[n] = base + (1 if n[0] == 'D' and n[1] not in done else 0)
    return {t: lvl[('D', t)] for t in g.tasks}

def simulate(g: Graph, workers: int, done: set[str] | None = None):
    """List scheduling on the event graph. A worker is busy only while a task's own work runs;
    completion prerequisites delay completion, not the worker. Priority: longest remaining path.
    Repository merge, review and CI capacity are not modelled. Returns makespan in size units."""
    done = set(done or set())
    adj = g.events()
    w = {t: SIZES[g.tasks[t]['size']] for t in g.tasks}
    succ = defaultdict(set)
    for n, ps in adj.items():
        for p in ps:
            succ[p].add(n)
    order, _ = g.event_order()
    rem = {}
    for n in reversed(order):
        rem[n] = (w[n[1]] if n[0] == 'D' else 0) + max((rem[s] for s in succ.get(n, ())), default=0)
    reached = set()
    for t in done:
        reached.add(('D', t)); reached.add(('C', t))
    time, running, heap, queued = 0.0, [], [], set()

    def settle():
        changed = True
        while changed:
            changed = False
            for t in g.tasks:
                c = ('C', t)
                if c not in reached and ('D', t) in reached and adj[c] <= reached:
                    reached.add(c); changed = True
            for t in g.tasks:
                d = ('D', t)
                if d in reached or t in queued:
                    continue
                if adj.get(d, set()) <= reached:
                    heapq.heappush(heap, (-rem[d], t)); queued.add(t)

    settle()
    while len(reached) < 2 * len(g.tasks):
        while heap and (workers <= 0 or len(running) < workers):
            _, t = heapq.heappop(heap)
            heapq.heappush(running, (time + w[t], t))
        if not running:
            raise Fail('simulation deadlock (unsatisfiable prerequisites)')
        end, t = heapq.heappop(running)
        time = end
        reached.add(('D', t))
        settle()
    return time


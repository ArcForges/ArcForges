def render_wp_block(g: Graph, wp: str, rel: str) -> str:
    L = Linker(g.design, rel)
    mapped = defaultdict(list)
    for t in g.data['tasks']:
        for o in t['obligations']:
            m = SUBSTEP.match(o['ref']) or POB_ID.match(o['ref'])
            if m and m[1] == wp:
                mapped[t['id']].append(o)
    own = sorted(mapped, key=lambda x: (g.tasks[x]['lane'], x))
    lines = [BEGIN, '',
             'Scheduling is task-level under [P2-018](../../decisions/phase-2-specification-decisions.md#rule-p2-018). '
             'This package is an obligation set; it is satisfied when every task below is complete with its evidence. '
             'Prerequisites are typed task edges, never "all upstream packages complete".', '',
             '| Delivery task | Satisfies | Start prerequisites outside this package |', '|---|---|---|']
    own_set = set(own)
    for tid in own:
        t = g.tasks[tid]
        sat = '<br>'.join(f'{obligation_link(g, L, o["ref"])} ({L.text(o["part"])})' for o in mapped[tid])
        ext = ', '.join(f'{task_link(g, e["task"], rel)} ({e["type"]})' for e in t['start'] if e['task'] not in own_set) or 'none'
        lines.append(f'| {task_link(g, tid, rel)} | {sat} | {ext} |')
    succ = g.succ_map()
    consumers = sorted({s for tid in own for s in succ.get(tid, ()) if s not in own_set})
    lines.append('')
    lines.append('**Consumers outside this package:** ' + (', '.join(task_link(g, c, rel) for c in consumers) or 'none') + '.')
    lines.append('')
    lines.append(END)
    if L.unknown:
        raise Fail(f'{rel}: unresolved identifiers {sorted(L.unknown)}')
    return '\n'.join(lines)

def splice(text: str, block: str) -> str:
    if BEGIN in text:
        pre, rest = text.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        return pre + block + post
    raise Fail('missing generated delivery block markers')

def design_views(g):
    """Render only the Design-owned views, using the canonical Plan algorithms."""
    result = {}
    for lane in g.data['lanes']:
        if any(t['lane'] == lane['id'] for t in g.data['tasks']):
            result[f'{DELIVERY_REL}/lanes/{lane["id"]}.md'] = render_lane(g, lane)
    for name, renderer in [('traceability', render_traceability), ('substitutes', render_substitutes),
                           ('shared-resources', render_resources), ('schedule-analysis', render_analysis)]:
        result[f'{DELIVERY_REL}/{name}.md'] = renderer(g)
    for wp, path in wp_files(g.design).items():
        text = path.read_text(encoding='utf-8')
        if BEGIN in text:
            relative = path.relative_to(g.design).as_posix()
            result[relative] = splice(text, render_wp_block(g, wp, relative))
    return result


def graph(root, docs=None):
    """Fail closed on malformed graph, stale views, and work-package structure."""
    docs = corpus.load(root) if docs is None else docs
    result = {'nodes': 0, 'edges': 0, 'activePackages': [], 'packages': {}, 'errors': []}
    try:
        data = load_json(root / GRAPH_REL)
        if data.get('schemaVersion') != 1 or type(data.get('schemaVersion')) is not int:
            raise ValueError('unsupported delivery graph schema')
        for name in ('tasks', 'lanes', 'repositories', 'adoptionSlices', 'substitutes', 'sharedResources', 'packageObligations'):
            rows = data.get(name)
            if not isinstance(rows, list) or any(not isinstance(row, dict) for row in rows):
                raise ValueError(f'{name}: expected record array')
            ids = [row['id'] for row in rows]
            if len(ids) != len(set(ids)):
                raise ValueError(f'{name}: duplicate identifier')
        allowed = {'DesktopPlatform', 'Contracts', 'ArcScope', 'Cloud', 'AI', 'Web', 'Mobile', 'Design', 'Plan'}
        if any(row['id'] not in allowed for row in data['repositories']):
            raise ValueError('unknown repository in delivery graph')
        # The caller can supply mutated documents for independent rejection fixtures.
        # Materialize data only; no code, hooks, or subprocesses run from this tree.
        with tempfile.TemporaryDirectory(prefix='arcforges-graph-docs-') as temporary:
            snapshot = Path(temporary)
            for name, text in docs.items():
                target = snapshot / name
                if not target.resolve().is_relative_to(snapshot.resolve()):
                    raise ValueError('documentation path escapes graph snapshot')
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding='utf-8', newline='\n')
            target = snapshot / GRAPH_REL
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(json.dumps(data), encoding='utf-8')
            model = Graph(snapshot)
            errors, warnings = validate(model)
            result['errors'].extend(errors)
            result['warnings'] = warnings
            active = {match[1] for task in model.data['tasks'] for obligation in task['obligations']
                      if (match := re.match(r'WP-(\d{2})[.:]', obligation['ref']))}
            result.update(nodes=len(model.tasks), edges=sum(len(model.starts(t)) + len(model.complete_edges(v))
                          for t, v in model.tasks.items()), activePackages=sorted(active))
            for name, text in docs.items():
                numbers = re.findall(r'^## (\d+(?:\.\d+)*)(?:\.)?\s', text, re.M)
                if len(numbers) != len(set(numbers)):
                    result['errors'].append([name, 'duplicate numbered section'])
                match = re.match(r'docs/planning/work-packages/(\d{2})-', name)
                if not match or match[1] not in active:
                    continue
                key = match[1]
                if key in result['packages']:
                    result['errors'].append([name, 'duplicate package identifier', key])
                result['packages'][key] = name
                if set(numbers) != {str(i) for i in range(1, 10)}:
                    result['errors'].append([name, 'mandatory sections'])
                evidence = text.split('## 7. ', 1)[-1].split('\n## ', 1)[0]
                rows = [line for line in evidence.splitlines() if line.startswith('|') and f'#rule-wp-{key}.90)' in line]
                if len(rows) != 1:
                    result['errors'].append([name, 'owned .90 evidence rows', len(rows)])
                if BEGIN not in text or END not in text:
                    result['errors'].append([name, 'missing generated package view'])
            if set(result['packages']) != active:
                result['errors'].append(['active package owner has no work-package source'])
            if not errors:
                generated = design_views(model)
                for name, expected in generated.items():
                    if docs.get(name) != expected:
                        result['errors'].append([name, 'generated view drift'])
                result['generatedViews'] = len(generated)
    except (OSError, ValueError, KeyError, TypeError, IndexError, AttributeError, RecursionError) as error:
        result['errors'].append([GRAPH_REL, str(error)])
    return result
